import { NextResponse } from "next/server";

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const { title, description, price, category } = body;

    const domain =
      process.env.SHOPIFY_STORE_DOMAIN?.replace(/"/g, "") ||
      "brotherhood-f5g25mtk.myshopify.com";

    // Dono variable names handle kiye hain taake koi mismatch na ho
    const token =
      process.env.SHOPIFY_ADMIN_API_ACCESS_TOKEN?.replace(/"/g, "") ||
      process.env.SHOPIFY_ADMIN_ACCESS_TOKEN?.replace(/"/g, "");

    const apiVersion =
      process.env.SHOPIFY_API_VERSION?.replace(/"/g, "") || "2024-01";

    if (!token) {
      return NextResponse.json(
        { error: "Shopify Admin Access Token missing in .env.local" },
        { status: 500 }
      );
    }

    // Modern Shopify GraphQL Mutation (Works in 2024, 2025, 2026+)
    const graphqlQuery = {
      query: `
        mutation productCreate($input: ProductInput!) {
          productCreate(input: $input) {
            product {
              id
              title
              status
              variants(first: 1) {
                edges {
                  node {
                    id
                    price
                  }
                }
              }
            }
            userErrors {
              field
              message
            }
          }
        }
      `,
      variables: {
        input: {
          title: title || "New AI Generated Product",
          descriptionHtml: `<p>${description || "High quality product generated by AI."}</p>`,
          productType: category || "General",
          status: "ACTIVE", // 🟢 Direct Active hoga taake catalog mein show ho!
          variants: [
            {
              price: String(price || "89.99"),
            },
          ],
        },
      },
    };

    const res = await fetch(
      `https://${domain}/admin/api/${apiVersion}/graphql.json`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "X-Shopify-Access-Token": token,
        },
        body: JSON.stringify(graphqlQuery),
      }
    );

    const json = await res.json();

    if (json.errors) {
      console.error("Shopify GraphQL Root Error:", json.errors);
      return NextResponse.json({ error: json.errors }, { status: 400 });
    }

    const userErrors = json?.data?.productCreate?.userErrors;
    if (userErrors && userErrors.length > 0) {
      console.error("Shopify Product Creation Errors:", userErrors);
      return NextResponse.json({ error: userErrors }, { status: 400 });
    }

    const createdProduct = json?.data?.productCreate?.product;
    return NextResponse.json({
      success: true,
      product: createdProduct,
      variantId: createdProduct?.variants?.edges?.[0]?.node?.id,
    });
  } catch (error: any) {
    console.error("Internal Server Error:", error);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}